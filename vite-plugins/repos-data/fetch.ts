import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { curatedRepos } from './config.js'

interface GitHubRepo {
  name: string
  description: string | null
  stargazerCount: number
  forkCount: number
  primaryLanguage: {
    name: string
    color: string
  } | null
  pushedAt: string
  url: string
  repositoryTopics: {
    nodes: Array<{
      topic: {
        name: string
      }
    }>
  }
  latestRelease: {
    tagName: string
    publishedAt: string
    url: string
  } | null
  defaultBranchRef: {
    target: {
      commitUrl: string
    }
  } | null
}

const formatTypeScriptValue = (value: unknown, indent = 0): string => {
  const spaces = '  '.repeat(indent)
  const nextSpaces = '  '.repeat(indent + 1)

  if (value === null) return 'null'
  if (typeof value === 'string') return JSON.stringify(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    const items = value.map(item => `${nextSpaces}${formatTypeScriptValue(item, indent + 1)}`).join(',\n')
    return `[\n${items}\n${spaces}]`
  }

  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>)
    if (entries.length === 0) return '{}'
    const props = entries
      .map(([key, val]) => `${nextSpaces}${JSON.stringify(key)}: ${formatTypeScriptValue(val, indent + 1)}`)
      .join(',\n')
    return `{\n${props}\n${spaces}}`
  }

  return String(value)
}

interface GraphQLResponse {
  data: Record<string, GitHubRepo>
  errors?: Array<{ message: string }>
}

const fetchRepoData = async (token: string): Promise<GitHubRepo[]> => {
  // Build GraphQL query with aliases for each repo
  const repoFragments = curatedRepos
    .map(
      (repo, index) => `
    repo${index}: repository(owner: "${repo.owner}", name: "${repo.name}") {
      name
      description
      stargazerCount
      forkCount
      primaryLanguage {
        name
        color
      }
      pushedAt
      url
      repositoryTopics(first: 10) {
        nodes {
          topic {
            name
          }
        }
      }
      latestRelease {
        tagName
        publishedAt
        url
      }
      defaultBranchRef {
        target {
          ... on Commit {
            commitUrl
          }
        }
      }
    }
  `,
    )
    .join('\n')

  const query = `
    query GetCuratedRepos {
      ${repoFragments}
    }
  `

  const response = await fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ query }),
  })

  if (!response.ok) throw new Error(`GitHub API request failed with status ${response.status}: ${response.statusText}`)

  const result = (await response.json()) as GraphQLResponse

  if (result.errors)
    throw new Error(`GitHub GraphQL API returned errors: ${result.errors.map((e) => e.message).join(', ')}`)

  if (!result.data) throw new Error('GitHub GraphQL API returned no data')

  // Convert the aliased response object to an array
  const repos = Object.values(result.data).filter((repo): repo is GitHubRepo => repo !== null)

  if (repos.length === 0) throw new Error('No repositories found in GitHub API response')

  return repos
}

export const fetchAndWriteRepos = async () => {
  const token = process.env.GITHUB_TOKEN

  if (!token) {
    throw new Error(
      'GITHUB_TOKEN environment variable is required. Run: gh auth token | xargs -I {} sh -c "GITHUB_TOKEN={} pnpm dev"',
    )
  }

  console.log('📦 Fetching repository data from GitHub...')

  const repos = await fetchRepoData(token)

  const data = {
    fetchedAt: new Date().toISOString(),
    repos,
  }

  // Generate TypeScript file content
  const tsContent = `/**
 * GitHub Repository Data
 *
 * This file is auto-generated by vite-plugins/repos-data
 * Do not edit manually - will be regenerated when missing
 *
 * Last updated: ${data.fetchedAt}
 */

import * as S from 'effect/Schema'
import { GitHubData } from './schemas/repos.js'

export const githubData = S.decodeUnknownSync(GitHubData)(${formatTypeScriptValue(data, 0)})

export const repos = githubData.repos
export const fetchedAt = githubData.fetchedAt
`

  const outputPath = join(process.cwd(), 'app', 'data', 'repos.ts')
  writeFileSync(outputPath, tsContent)

  console.log(`✅ Successfully fetched ${repos.length} repositories`)
  console.log(`✅ Data saved to ${outputPath}`)
  console.log(`✅ Fetched at: ${data.fetchedAt}`)
  console.log('\nRepositories:')
  repos.forEach((repo) => {
    console.log(`  - ${repo.name} (⭐ ${repo.stargazerCount})`)
  })
}
